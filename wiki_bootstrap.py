"""Initial pass that fills wiki/ with one brief per top author / category / ticker.

Reads:
  - categorized_tweets.json  (the classifier's output)
  - wiki/CLAUDE.md           (the schema contract)

Writes:
  - wiki/people/<handle>.md
  - wiki/concepts/<slug>.md
  - wiki/tickers/<symbol>.md
  - wiki/CHANGELOG.md (append)
  - wiki/index.md     (rewrite the machine-managed sections)

Each page is generated by the chat model - never hand-derived from the source
tweets without going through the LLM - because the brief shape *is* the
schema, and the schema lives in wiki/CLAUDE.md as a prompt. The script's job
is to gather the right inputs (tweets), set the right system prompt (the
schema doc), and persist the response.

Usage:
    pip install anthropic httpx
    export ANTHROPIC_API_KEY=sk-ant-...

    python wiki_bootstrap.py --dry-run       # prints what it would do
    python wiki_bootstrap.py --limit-authors 20 \\
        --limit-concepts 20 --limit-tickers 20   # validation slice
    python wiki_bootstrap.py                  # full pass

By default we use claude-haiku-4-5 - small enough that the validation slice
costs <$1, and the full pass on this archive (~26k tweets, top 100 of each
type) lands under ~$3.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
import time
from collections import Counter, defaultdict
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterable

ROOT = Path(__file__).resolve().parent
WIKI = ROOT / "wiki"
SCHEMA_DOC = WIKI / "CLAUDE.md"
SCHEMA_TEMPLATE = ROOT / "docs" / "wiki-schema.md"
INPUT_JSON = ROOT / "categorized_tweets.json"
CATEGORIES = {"people", "concepts", "tickers"}

DEFAULT_MODEL = "claude-haiku-4-5"
TICKER_RE = re.compile(r"\$([A-Z]{2,6})\b")
SLUG_RE = re.compile(r"[^a-z0-9]+")


def _slugify(s: str) -> str:
    return SLUG_RE.sub("-", s.lower()).strip("-")


def _now_iso() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _read_schema_doc() -> str:
    """Return the schema text. On a fresh clone, copy the template first.

    wiki/ is gitignored, so wiki/CLAUDE.md does not exist after a clone.
    The template at docs/wiki-schema.md is the default. Edit wiki/CLAUDE.md
    afterwards to change the page format. The script never overwrites it.
    """
    if not SCHEMA_DOC.is_file():
        if not SCHEMA_TEMPLATE.is_file():
            sys.exit(f"missing {SCHEMA_DOC} and the template {SCHEMA_TEMPLATE}")
        WIKI.mkdir(parents=True, exist_ok=True)
        SCHEMA_DOC.write_text(SCHEMA_TEMPLATE.read_text(encoding="utf-8"), encoding="utf-8")
        print(f"Created {SCHEMA_DOC} from {SCHEMA_TEMPLATE.relative_to(ROOT)}")
    return SCHEMA_DOC.read_text(encoding="utf-8")


def _load_tweets() -> list[dict[str, Any]]:
    if not INPUT_JSON.is_file():
        sys.exit(f"missing {INPUT_JSON}; run parse_and_classify.py first")
    return json.loads(INPUT_JSON.read_text(encoding="utf-8"))["tweets"]


def _top_authors(tweets: list[dict[str, Any]], limit: int) -> list[tuple[str, int]]:
    counts: Counter[str] = Counter()
    for t in tweets:
        h = (t.get("handle") or "").lstrip("@").strip().lower()
        if h:
            counts[h] += 1
    return counts.most_common(limit)


def _top_concepts(tweets: list[dict[str, Any]], limit: int) -> list[tuple[str, int]]:
    counts: Counter[str] = Counter()
    for t in tweets:
        for c in t.get("categories", []) or []:
            # Take leaf or full path. We deduplicate by leaf.
            leaf = c.split(">")[-1].strip()
            if leaf:
                counts[leaf] += 1
    return counts.most_common(limit)


def _top_tickers(tweets: list[dict[str, Any]], limit: int) -> list[tuple[str, int]]:
    counts: Counter[str] = Counter()
    for t in tweets:
        for m in TICKER_RE.findall(t.get("text") or ""):
            counts[m.upper()] += 1
    return counts.most_common(limit)


def _tweets_by_author(tweets: list[dict[str, Any]], handle: str, n: int = 30) -> list[dict[str, Any]]:
    h = handle.lower()
    matches = [
        t for t in tweets if (t.get("handle") or "").lstrip("@").lower() == h
    ]
    matches.sort(key=lambda t: int(t.get("like_count", 0) or 0), reverse=True)
    return matches[:n]


def _tweets_by_concept(tweets: list[dict[str, Any]], leaf: str, n: int = 30) -> list[dict[str, Any]]:
    matches = [
        t for t in tweets if any(leaf in (c or "") for c in (t.get("categories") or []))
    ]
    matches.sort(key=lambda t: int(t.get("like_count", 0) or 0), reverse=True)
    return matches[:n]


def _tweets_by_ticker(tweets: list[dict[str, Any]], symbol: str, n: int = 30) -> list[dict[str, Any]]:
    sym = symbol.upper()
    matches = [
        t for t in tweets if f"${sym}" in (t.get("text") or "").upper()
    ]
    matches.sort(key=lambda t: int(t.get("like_count", 0) or 0), reverse=True)
    return matches[:n]


def _format_tweet_input(t: dict[str, Any]) -> str:
    return (
        f"[id={t.get('id')}] @{(t.get('handle') or '').lstrip('@')} ({t.get('timestamp', '')})\n"
        f"{(t.get('text') or '').strip()}"
    )


def _build_prompt(
    *,
    schema_doc: str,
    page_type: str,
    page_slug: str,
    page_display: str,
    seed_tweets: list[dict[str, Any]],
) -> tuple[str, str]:
    """Returns (system_prompt, user_message)."""
    system = (
        "You are the curator of the user's personal Trove wiki. The schema "
        "below is the contract - every page you produce MUST match it. Never "
        "fabricate beyond the source tweets; every claim cites a tweet id.\n\n"
        "=== wiki/CLAUDE.md (schema) ===\n"
        f"{schema_doc}\n"
        "=== end schema ===\n\n"
        "Output ONLY the page contents (frontmatter + markdown body). No "
        "code fences, no commentary outside the page."
    )
    tweet_block = "\n\n".join(_format_tweet_input(t) for t in seed_tweets)
    user = (
        f"Write a `{page_type}` page for `{page_slug}` (display: \"{page_display}\").\n"
        f"Use only the {len(seed_tweets)} source tweets below. Set "
        "`source_tweet_ids` to those ids. Set `last_updated_iso` to the "
        f"current UTC time `{_now_iso()}`. Set `last_updated_by` to "
        "`bootstrap`. Pick `confidence` honestly: high if ≥10 tweets paint a "
        "consistent picture, medium if 3-9, low otherwise.\n\n"
        f"=== source tweets ({len(seed_tweets)}) ===\n{tweet_block}"
    )
    return system, user


def _call_anthropic(
    *, system: str, user: str, model: str, max_tokens: int = 1500
) -> str:
    import anthropic  # local import so --dry-run doesn't require the SDK

    client = anthropic.Anthropic()
    for attempt in range(4):
        try:
            resp = client.messages.create(
                model=model,
                max_tokens=max_tokens,
                system=system,
                messages=[{"role": "user", "content": user}],
            )
            blocks = resp.content
            text_parts = [b.text for b in blocks if getattr(b, "type", "") == "text"]
            return "".join(text_parts).strip()
        except Exception as e:  # pragma: no cover (network)
            wait = 2 ** attempt
            print(f"  retry {attempt + 1}/4 after error: {e!r} (sleeping {wait}s)", file=sys.stderr)
            time.sleep(wait)
    raise RuntimeError("Anthropic call failed after 4 attempts")


_CODE_FENCE_RE = re.compile(r"^```[a-zA-Z]*\n(.*)\n```\s*$", re.DOTALL)


def _write_page(path: Path, content: str, *, dry_run: bool) -> None:
    # Strip a wrapping ```markdown fence the model occasionally adds despite
    # the system prompt; otherwise leave content as-is.
    m = _CODE_FENCE_RE.match(content.strip())
    if m:
        content = m.group(1)
    content = content.lstrip()
    if not content.startswith("---"):
        # Surface the model's deviation rather than silently rewriting it.
        print(f"  ! {path}: response missing frontmatter, skipping", file=sys.stderr)
        print(f"    first 80 chars: {content[:80]!r}", file=sys.stderr)
        return
    if dry_run:
        print(f"  [dry] would write {path} ({len(content)} chars)")
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content.rstrip() + "\n", encoding="utf-8")


def _append_changelog(verb: str, path_rel: str, note: str, *, dry_run: bool) -> None:
    line = f"{_now_iso()}  bootstrap   {verb:<5} {path_rel:<30} {note}"
    if dry_run:
        print(f"  [dry] would log: {line}")
        return
    log = WIKI / "CHANGELOG.md"
    with log.open("a", encoding="utf-8") as f:
        f.write(line + "\n")


def _rewrite_index(*, dry_run: bool) -> None:
    """Rewrite the machine-managed half of wiki/index.md."""
    if dry_run:
        print("  [dry] would rewrite wiki/index.md machine sections")
        return
    index = WIKI / "index.md"
    if index.is_file():
        existing = index.read_text(encoding="utf-8")
        marker = "<!-- machine-managed below -->"
        head, _, _ = existing.partition(marker)
        if not _:
            head = existing.rstrip() + "\n\n" + marker + "\n"
        else:
            head = head + marker + "\n"
    else:
        head = "# Wiki index\n\n<!-- machine-managed below -->\n"

    sections: dict[str, list[str]] = {"people": [], "concepts": [], "tickers": []}
    for cat in CATEGORIES:
        d = WIKI / cat
        if not d.is_dir():
            continue
        for f in sorted(d.glob("*.md")):
            slug = f.stem
            display = slug
            text = f.read_text(encoding="utf-8")
            m = re.search(r'^display:\s*"?([^"\n]+)"?', text, re.MULTILINE)
            if m:
                display = m.group(1).strip()
            sections[cat].append(f"- [[{cat}/{slug}]] - {display}")

    body = [head.rstrip(), ""]
    body.append("## People")
    body.extend(sections["people"] or ["_(empty)_"])
    body.append("")
    body.append("## Concepts")
    body.extend(sections["concepts"] or ["_(empty)_"])
    body.append("")
    body.append("## Tickers")
    body.extend(sections["tickers"] or ["_(empty)_"])
    body.append("")
    index.write_text("\n".join(body), encoding="utf-8")


def _existing_pages(category: str) -> set[str]:
    d = WIKI / category
    if not d.is_dir():
        return set()
    return {f.stem for f in d.glob("*.md")}


def _gate_or_run(
    *,
    label: str,
    items: list[tuple[str, int]],
    pick_tweets,
    page_type: str,
    folder: str,
    schema_doc: str,
    model: str,
    dry_run: bool,
    skip_existing: bool,
    limit: int | None,
) -> int:
    if limit is not None:
        items = items[:limit]
    print(f"\n[{label}] {len(items)} target(s) (model={model})")
    written = 0
    existing = _existing_pages(folder)
    for idx, (key, count) in enumerate(items, 1):
        slug = _slugify(key)
        if skip_existing and slug in existing:
            print(f"  ({idx}/{len(items)}) {slug} - exists, skipping")
            continue
        seeds = pick_tweets(key)
        if not seeds:
            print(f"  ({idx}/{len(items)}) {slug} - no seed tweets, skipping")
            continue
        display = key if page_type != "person" else f"@{key}"
        print(
            f"  ({idx}/{len(items)}) {slug} - {count} tweets in archive, "
            f"using {len(seeds)} seeds"
        )
        if dry_run:
            written += 1
            continue
        system, user = _build_prompt(
            schema_doc=schema_doc,
            page_type=page_type,
            page_slug=slug,
            page_display=display,
            seed_tweets=seeds,
        )
        out = _call_anthropic(system=system, user=user, model=model)
        path = WIKI / folder / f"{slug}.md"
        _write_page(path, out, dry_run=False)
        _append_changelog("add", f"{folder}/{slug}", f"first pass ({count} tweets)", dry_run=False)
        written += 1
    return written


def main() -> None:
    parser = argparse.ArgumentParser(description="bootstrap the wiki/ from categorized_tweets.json")
    parser.add_argument("--limit-authors", type=int, default=None)
    parser.add_argument("--limit-concepts", type=int, default=None)
    parser.add_argument("--limit-tickers", type=int, default=None)
    parser.add_argument("--ticker-min-mentions", type=int, default=3)
    parser.add_argument(
        "--skip-existing",
        action="store_true",
        default=True,
        help="don't regenerate pages that already exist (default on)",
    )
    parser.add_argument(
        "--no-skip-existing", dest="skip_existing", action="store_false"
    )
    parser.add_argument("--model", default=DEFAULT_MODEL)
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    if not args.dry_run and not os.environ.get("ANTHROPIC_API_KEY"):
        sys.exit("ANTHROPIC_API_KEY env var required (or use --dry-run)")

    schema_doc = _read_schema_doc()
    tweets = _load_tweets()
    print(f"Loaded {len(tweets)} tweets from {INPUT_JSON.name}")

    authors = _top_authors(tweets, args.limit_authors or 100)
    concepts = _top_concepts(tweets, args.limit_concepts or 100)
    tickers = [
        (t, c) for t, c in _top_tickers(tweets, args.limit_tickers or 100)
        if c >= args.ticker_min_mentions
    ]

    written_a = _gate_or_run(
        label="people",
        items=authors,
        pick_tweets=lambda h: _tweets_by_author(tweets, h),
        page_type="person",
        folder="people",
        schema_doc=schema_doc,
        model=args.model,
        dry_run=args.dry_run,
        skip_existing=args.skip_existing,
        limit=args.limit_authors,
    )

    written_c = _gate_or_run(
        label="concepts",
        items=concepts,
        pick_tweets=lambda c: _tweets_by_concept(tweets, c),
        page_type="concept",
        folder="concepts",
        schema_doc=schema_doc,
        model=args.model,
        dry_run=args.dry_run,
        skip_existing=args.skip_existing,
        limit=args.limit_concepts,
    )

    written_t = _gate_or_run(
        label="tickers",
        items=tickers,
        pick_tweets=lambda s: _tweets_by_ticker(tweets, s),
        page_type="ticker",
        folder="tickers",
        schema_doc=schema_doc,
        model=args.model,
        dry_run=args.dry_run,
        skip_existing=args.skip_existing,
        limit=args.limit_tickers,
    )

    _rewrite_index(dry_run=args.dry_run)

    print(
        f"\nDone - wrote {written_a} people, {written_c} concepts, "
        f"{written_t} tickers"
        + (" (dry run, no files modified)" if args.dry_run else "")
    )


if __name__ == "__main__":
    main()
