import { useEffect, useRef } from 'react';
import { Link, useLocation } from 'react-router-dom';

interface Props {
  open: boolean;
  onClose: () => void;
}

const items = [
  { to: '/articles', label: 'Articles', icon: ArticlesIcon },
  { to: '/list-accounts', label: 'List Accounts', icon: ListAccountsIcon },
  { to: '/categories', label: 'Categories', icon: CategoriesIcon },
  { to: '/import', label: 'Import', icon: ImportIcon },
  { to: '/settings', label: 'Settings', icon: SettingsIcon },
];

export function MobileMoreSheet({ open, onClose }: Props) {
  const location = useLocation();
  const panelRef = useRef<HTMLDivElement | null>(null);

  useEffect(() => {
    if (!open) return;
    const onDown = (e: MouseEvent) => {
      if (panelRef.current?.contains(e.target as Node)) return;
      onClose();
    };
    const onKey = (e: KeyboardEvent) => {
      if (e.key === 'Escape') onClose();
    };
    window.addEventListener('mousedown', onDown);
    window.addEventListener('keydown', onKey);
    return () => {
      window.removeEventListener('mousedown', onDown);
      window.removeEventListener('keydown', onKey);
    };
  }, [open, onClose]);

  if (!open) return null;

  return (
    <div
      className="fixed inset-0 z-50 flex items-end bg-ink-900/30 backdrop-blur-sm md:hidden"
      onClick={onClose}
      aria-modal="true"
      role="dialog"
    >
      <div
        ref={panelRef}
        className="w-full rounded-t-[24px] border-t border-white/20 bg-white/95 p-4 pb-[calc(1rem+env(safe-area-inset-bottom))] shadow-[0_-8px_32px_rgba(0,0,0,0.12)] backdrop-blur-xl dark:border-white/10 dark:bg-ink-900/95"
        onClick={(e) => e.stopPropagation()}
      >
        <div className="mx-auto mb-4 h-1 w-10 rounded-full bg-ink-300/50" />
        <nav className="space-y-1">
          {items.map((item) => {
            const active = location.pathname === item.to;
            return (
              <Link
                key={item.to}
                to={{ pathname: item.to, search: location.search }}
                onClick={onClose}
                className={`flex min-h-[48px] items-center gap-3 rounded-xl px-3 text-sm font-medium transition-colors ${
                  active
                    ? 'bg-ios-blue/10 text-ios-blue dark:bg-ios-blue/20 dark:text-ios-teal'
                    : 'text-ink-800 hover:bg-canvas-100 dark:text-ink-100 dark:hover:bg-white/5'
                }`}
              >
                <item.icon className="h-5 w-5" />
                {item.label}
              </Link>
            );
          })}
        </nav>
        <button
          type="button"
          onClick={onClose}
          className="mt-3 w-full rounded-xl bg-canvas-100 py-3 text-sm font-semibold text-ink-800 dark:bg-white/10 dark:text-ink-100"
        >
          Cancel
        </button>
      </div>
    </div>
  );
}

